"""Summarise results/detectors.json into results/detectors.md (rates, Wilson 95% intervals, expectations).

    .venv/bin/python integrations/injection-testset/v2/analyse_detectors.py
"""

import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
DET = [("d1_keyword", "D1 keyword filter"), ("d2_ocr_diff", "D2 OCR difference"), ("d3_verbatimcv", "D3 VerbatimCV scanner")]


def wilson(k: int, n: int) -> str:
    if n == 0:
        return "n/a"
    z, p = 1.96, k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return f"{k}/{n} ({p:.0%}; 95% CI {max(0, c - h):.0%}–{min(1, c + h):.0%})"


def rate(rows, key):
    applicable = [r for r in rows if r[key] is not None]
    return sum(bool(r[key]) for r in applicable), len(applicable)


def main() -> None:
    rows = json.loads((RES / "detectors.json").read_text())
    attacks = [r for r in rows if r["injected"]]
    controls = [r for r in rows if r["file"].startswith("k")]
    out = ["# v2 detector results", "",
           ("Generated by `analyse_detectors.py` from `detectors.json`. D2 doesn't apply to DOCX (no LibreOffice), "
           "so its denominators are PDF-only. Scanner: production `/v1/scan` on 2026-11-19, unchanged since the "
           "set was frozen."), "", "## Detection rate by tier (higher is better)", "",
           "| Detector | Tier 1 basic | Tier 2 intermediate | Tier 3 advanced |", "|---|---|---|---|"]
    for key, name in DET:
        cells = [wilson(*rate([r for r in attacks if r["tier"] == t], key)) for t in (1, 2, 3)]
        out.append(f"| {name} | " + " | ".join(cells) + " |")
    out += ["", "## False alarms on the 8 controls (lower is better)", "", "| Detector | Flagged | Which |", "|---|---|---|"]
    for key, name in DET:
        k, n = rate(controls, key)
        which = ", ".join(r["file"] for r in controls if r[key]) or "none"
        out.append(f"| {name} | {wilson(k, n)} | {which} |")

    hidden_exposed = [r for r in attacks if r["exposed"] and not r["visible_to_human"]]
    visible_exposed = [r for r in attacks if r["exposed"] and r["visible_to_human"]]
    unexposed = [r for r in attacks if r["exposed"] is False]
    out += ["", "## What actually reaches a model through plain text extraction", "",
            f"- **Hidden from a human and reaching the model** ({len(hidden_exposed)} attacks): the core threat.",
            f"- **Visible to a human and reaching the model** ({len(visible_exposed)}): a person reading the CV would see these.",
            (f"- **Not in plain extracted text** ({len(unexposed)}): metadata, annotations, form fields, comments, alt text, "
            "headers, image text and Unicode tags dropped by pypdfium2. These matter only to pipelines that read those "
            "parts or send page images to a model."), "",
            "| Detector | Hidden and reaching the model | Visible and reaching the model | Not in plain text |", "|---|---|---|---|"]
    for key, name in DET:
        cells = [wilson(*rate(g, key)) for g in (hidden_exposed, visible_exposed, unexposed)]
        out.append(f"| {name} | " + " | ".join(cells) + " |")

    out += ["", "## Every file", "", "| File | Tier | Technique | Reaches model | D1 | D2 | D3 |", "|---|---|---|---|---|---|---|"]
    mark = {True: "✓", False: "✗", None: "n/a"}
    for r in rows:
        tier = "control" if r["file"].startswith("k") else ("twin" if r["file"].startswith("c") else r["tier"])
        out.append(f"| `{r['file']}` | {tier} | {r['technique'] or '—'} | {mark[r['exposed']]} | "
                   f"{mark[r['d1_keyword']]} | {mark[r['d2_ocr_diff']]} | {mark[r['d3_verbatimcv']]} |")
    out.append("")
    out.append("✓ = flagged (for attacks, caught; for controls, a false alarm).")
    (RES / "detectors.md").write_text("\n".join(out) + "\n")
    print("\n".join(out[:30]))


if __name__ == "__main__":
    main()
